    /** Fills the table; if filter is not empty only matching patient names are shown. */
    private void loadAppointments(String filter) {
        javax.swing.table.DefaultTableModel model =
                (javax.swing.table.DefaultTableModel) tblAppointments.getModel();
        model.setRowCount(0);
        String f = filter.toLowerCase();
        for (Appointment a : tower.appointments) {
            if (!f.isEmpty() && !a.patient.name.toLowerCase().contains(f)) {
                continue;
            }
            model.addRow(new Object[]{
                a.appointmentid,
                a.patient.name,
                a.patient.age,
                a.patient.condition,
                a.doctor.name,
                a.doctor.specialty,
                a.date,
                a.time,
                a.status
            });
        }
    }

    /** Changes the status of the selected appointment (Done / Cancelled). */
    private void changeStatus(String newStatus) {
        int viewRow = tblAppointments.getSelectedRow();
        if (viewRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select an appointment first.",
                    "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int id = (int) tblAppointments.getValueAt(viewRow, 0);

        for (Appointment a : tower.appointments) {
            if (a.appointmentid == id) {
                if ("Cancelled".equals(a.status) || "Done".equals(a.status)) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "This appointment is already " + a.status + ".",
                            "Info", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                    return;
                }
                int ok = javax.swing.JOptionPane.showConfirmDialog(this,
                        "Set appointment #" + id + " to \"" + newStatus + "\"?",
                        "Confirm", javax.swing.JOptionPane.YES_NO_OPTION);
                if (ok == javax.swing.JOptionPane.YES_OPTION) {
                    a.status = newStatus;
                    loadAppointments(txtSearch.getText().trim());
                }
                return;
            }
        }
    }

    /** Styles a table: centered cells, zebra rows, blue header. */
    private void styleTable(javax.swing.JTable table) {
        final java.awt.Color blue = new java.awt.Color(11, 110, 153);
        final java.awt.Color darkBlue = new java.awt.Color(11, 79, 113);
        final java.awt.Color altRow = new java.awt.Color(232, 241, 247);
        final java.awt.Color textColor = new java.awt.Color(38, 50, 56);

        table.setRowHeight(36);
        table.setFillsViewportHeight(true);
        table.setShowGrid(true);
        table.setIntercellSpacing(new java.awt.Dimension(1, 1));
        table.setAutoCreateRowSorter(true);
        table.getTableHeader().setReorderingAllowed(false);
        table.getTableHeader().setPreferredSize(new java.awt.Dimension(100, 40));

        javax.swing.table.DefaultTableCellRenderer cellRenderer = new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable t, Object value,
                    boolean selected, boolean focus, int row, int col) {
                super.getTableCellRendererComponent(t, value, selected, false, row, col);
                setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
                setOpaque(true);
                if (selected) {
                    setBackground(blue);
                    setForeground(java.awt.Color.WHITE);
                } else {
                    setBackground(row % 2 == 0 ? java.awt.Color.WHITE : altRow);
                    setForeground(textColor);
                }
                return this;
            }
        };
        for (int i = 0; i < table.getColumnCount(); i++) {
            table.getColumnModel().getColumn(i).setCellRenderer(cellRenderer);
        }

        table.getTableHeader().setDefaultRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable t, Object value,
                    boolean selected, boolean focus, int row, int col) {
                super.getTableCellRendererComponent(t, value, false, false, row, col);
                setHorizontalAlignment(javax.swing.SwingConstants.CENTER);
                setOpaque(true);
                setBackground(blue);
                setForeground(java.awt.Color.WHITE);
                setFont(new java.awt.Font("Arial", java.awt.Font.BOLD, 14));
                setBorder(javax.swing.BorderFactory.createMatteBorder(0, 0, 0, 1, darkBlue));
                return this;
            }
        });
    }

