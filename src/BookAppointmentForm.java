    /** Validates the form and saves the appointment. */
    private void save() {
        String name = txtName.getText().trim();
        String condition = txtCondition.getText().trim();
        String ageText = txtAge.getText().trim();
        String dateText = txtDate.getText().trim();

        if (name.isEmpty() || condition.isEmpty() || ageText.isEmpty() || dateText.isEmpty()) {
            warn("Please fill in all fields.");
            return;
        }

        int age;
        try {
            age = Integer.parseInt(ageText);
            if (age <= 0 || age > 120) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            warn("Age must be a whole number between 1 and 120.");
            return;
        }

        java.time.LocalDate date;
        try {
            date = java.time.LocalDate.parse(dateText);
        } catch (java.time.format.DateTimeParseException ex) {
            warn("Invalid date. Use the format yyyy-MM-dd, e.g. 2026-10-20");
            return;
        }
        if (date.isBefore(java.time.LocalDate.now())) {
            warn("The date cannot be in the past.");
            return;
        }

        if (cmbDoctor.getSelectedIndex() < 0) {
            warn("Please choose a doctor.");
            return;
        }
        Doctor doctor = tower.doctors.get(cmbDoctor.getSelectedIndex());
        String time = (String) cmbTime.getSelectedItem();
        String dateStr = date.toString();

        // Prevent double booking (cancelled appointments do not count)
        for (Appointment a : tower.appointments) {
            if (a.doctor == doctor && a.date.equals(dateStr) && a.time.equals(time)
                    && !"Cancelled".equals(a.status)) {
                warn("This doctor is already booked at that date and time.\nPlease choose another time.");
                return;
            }
        }

        tower.addAppointment(name, age, condition, doctor, dateStr, time);

        javax.swing.JOptionPane.showMessageDialog(this,
                "Appointment booked successfully!\n\nPatient: " + name
                + "\nDoctor: " + doctor.name
                + "\nDate: " + dateStr + "  " + time,
                "Success", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        dispose();
    }

    private void warn(String msg) {
        javax.swing.JOptionPane.showMessageDialog(this, msg, "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
    }

